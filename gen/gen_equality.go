// generateEqualityMethodsWithFS generates Equal() and Hash() methods using a FileSystem
func (g *Generator) generateEqualityMethodsWithFS(fs FileSystem, pkgName string) error {
	for _, spec := range g.equalitySpecs {
		if err := g.generateEqualMethod(spec, pkgName, fs); err != nil {
			return errors.Wrapf(err, "generate Equal for %s", spec.TypeName)
		}
		if err := g.generateHashMethod(spec, pkgName, fs); err != nil {
			return errors.Wrapf(err, "generate Hash for %s", spec.TypeName)
		}
	}
	return nil
}

// generateEqualMethod generates an Equal() method for a type
func (g *Generator) generateEqualMethod(spec *ir.EqualityMethodSpec, pkgName string, fs FileSystem) error {
	var b strings.Builder

	// File header comment
	fmt.Fprintf(&b, "// Code generated by ogen, DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkgName)

	// Method signature
	if spec.NeedsDepthTracking {
		fmt.Fprintf(&b, "// Equal compares two %s instances for equality.\n", spec.TypeName)
		fmt.Fprintf(&b, "// The depth parameter prevents infinite recursion on nested objects.\n")
		fmt.Fprintf(&b, "func (a %s) Equal(b %s, depth int) bool {\n", spec.TypeName, spec.TypeName)

		// Depth limit check
		fmt.Fprintf(&b, "\tif depth > %d {\n", spec.MaxDepth)
		fmt.Fprintf(&b, "\t\tpanic(&validate.DepthLimitError{\n")
		fmt.Fprintf(&b, "\t\t\tMaxDepth: %d,\n", spec.MaxDepth)
		fmt.Fprintf(&b, "\t\t\tTypeName: %q,\n", spec.TypeName)
		fmt.Fprintf(&b, "\t\t})\n")
		fmt.Fprintf(&b, "\t}\n\n")
	} else {
		fmt.Fprintf(&b, "// Equal compares two %s instances for equality.\n", spec.TypeName)
		fmt.Fprintf(&b, "func (a %s) Equal(b %s) bool {\n", spec.TypeName, spec.TypeName)
	}

	// Generate field comparisons
	for _, field := range spec.Fields {
		g.writeFieldComparison(&b, field, spec.NeedsDepthTracking)
	}

	fmt.Fprintf(&b, "\treturn true\n")
	fmt.Fprintf(&b, "}\n")

	// Write to file
	filename := fmt.Sprintf("oas_%s_equal_gen.go", snakeCase(spec.TypeName))
	return writeFormattedCode(fs, filename, []byte(b.String()))
}

// writeFieldComparison generates comparison code for a single field
func (g *Generator) writeFieldComparison(b *strings.Builder, field ir.FieldEqualitySpec, hasDepth bool) {
	switch field.FieldType {
	case ir.FieldTypePrimitive:
		switch {
		case field.IsRawJSON:
			// Raw JSON values compare semantically, not byte by byte
			fmt.Fprintf(b, "\t// Compare raw JSON field: %s\n", field.FieldName)
			fmt.Fprintf(b, "\tif !validate.EqualRawJSON(a.%s, b.%s) {\n", field.FieldName, field.FieldName)
			fmt.Fprintf(b, "\t\treturn false\n")
			fmt.Fprintf(b, "\t}\n")
		case field.IsByteSlice:
			// Byte slices need bytes.Equal()
			fmt.Fprintf(b, "\t// Compare byte slice field: %s\n", field.FieldName)
			if field.IsNilSemanticByteSlice {
				// nil encodes an absent or null value, which differs from
				// present empty bytes
				fmt.Fprintf(b, "\tif (a.%s == nil) != (b.%s == nil) {\n", field.FieldName, field.FieldName)
				fmt.Fprintf(b, "\t\treturn false\n")
				fmt.Fprintf(b, "\t}\n")
			}
			fmt.Fprintf(b, "\tif !bytes.Equal(a.%s, b.%s) {\n", field.FieldName, field.FieldName)
			fmt.Fprintf(b, "\t\treturn false\n")
			fmt.Fprintf(b, "\t}\n")
		case field.IsURL:
			// url.URL contains a pointer, so == compares identity
			fmt.Fprintf(b, "\t// Compare URL field by value: %s\n", field.FieldName)
			fmt.Fprintf(b, "\tif a.%s.String() != b.%s.String() {\n", field.FieldName, field.FieldName)
			fmt.Fprintf(b, "\t\treturn false\n")
			fmt.Fprintf(b, "\t}\n")
		case field.IsDecimal:
			// decimal.Decimal contains a pointer, so == compares identity
			fmt.Fprintf(b, "\t// Compare decimal field by value: %s\n", field.FieldName)
			fmt.Fprintf(b, "\tif !a.%s.Equal(b.%s) {\n", field.FieldName, field.FieldName)
			fmt.Fprintf(b, "\t\treturn false\n")
			fmt.Fprintf(b, "\t}\n")
		case field.IsDeepOnly:
			// No == operator for this type
			fmt.Fprintf(b, "\t// Compare field without == operator: %s\n", field.FieldName)
			fmt.Fprintf(b, "\tif !validate.EqualDeep(a.%s, b.%s) {\n", field.FieldName, field.FieldName)
			fmt.Fprintf(b, "\t\treturn false\n")
			fmt.Fprintf(b, "\t}\n")
		default:
			// Simple equality check
			fmt.Fprintf(b, "\tif a.%s != b.%s {\n", field.FieldName, field.FieldName)
			fmt.Fprintf(b, "\t\treturn false\n")
			fmt.Fprintf(b, "\t}\n")
		}

	case ir.FieldTypeOptional:
		// Optional field comparison (OptT and OptNilT types)
		fmt.Fprintf(b, "\t// Compare optional field: %s\n", field.FieldName)
		fmt.Fprintf(b, "\tif a.%s.Set != b.%s.Set {\n", field.FieldName, field.FieldName)
		fmt.Fprintf(b, "\t\treturn false\n")
		fmt.Fprintf(b, "\t}\n")
		fmt.Fprintf(b, "\tif a.%s.Set {\n", field.FieldName)
		valueIndent := "\t\t"
		if field.IsOptionalNullable {
			fmt.Fprintf(b, "\t\tif a.%s.Null != b.%s.Null {\n", field.FieldName, field.FieldName)
			fmt.Fprintf(b, "\t\t\treturn false\n")
			fmt.Fprintf(b, "\t\t}\n")
			fmt.Fprintf(b, "\t\tif !a.%s.Null {\n", field.FieldName)
			valueIndent = "\t\t\t"
		}
		switch {
		case field.IsNested:
			// Optional wrapper around nested object - call Equal()
			if hasDepth {
				fmt.Fprintf(b, "%sif !a.%s.Value.Equal(b.%s.Value, depth+1) {\n", valueIndent, field.FieldName, field.FieldName)
			} else {
				fmt.Fprintf(b, "%sif !a.%s.Value.Equal(b.%s.Value) {\n", valueIndent, field.FieldName, field.FieldName)
			}
			fmt.Fprintf(b, "%s\treturn false\n", valueIndent)
			fmt.Fprintf(b, "%s}\n", valueIndent)
		case field.IsMap:
			// Optional wrapper around map - need custom comparison
			g.writeMapComparison(b, fmt.Sprintf("a.%s.Value", field.FieldName), fmt.Sprintf("b.%s.Value", field.FieldName), valueIndent, field, hasDepth)
		case field.IsArray:
			// Optional wrapper around array - need iteration
			aArray := fmt.Sprintf("a.%s.Value", field.FieldName)
			bArray := fmt.Sprintf("b.%s.Value", field.FieldName)
			g.writeArrayComparisonWithNullable(b, aArray, bArray, valueIndent, field, hasDepth)
		case field.IsRawJSON:
			// Optional wrapper around raw JSON - compare semantically
			fmt.Fprintf(b, "%sif !validate.EqualRawJSON(a.%s.Value, b.%s.Value) {\n", valueIndent, field.FieldName, field.FieldName)
			fmt.Fprintf(b, "%s\treturn false\n", valueIndent)
			fmt.Fprintf(b, "%s}\n", valueIndent)
		case field.IsByteSlice:
			// Optional wrapper around byte slice - use bytes.Equal()
			fmt.Fprintf(b, "%sif !bytes.Equal(a.%s.Value, b.%s.Value) {\n", valueIndent, field.FieldName, field.FieldName)
			fmt.Fprintf(b, "%s\treturn false\n", valueIndent)
			fmt.Fprintf(b, "%s}\n", valueIndent)
		case field.IsURL:
			// Optional wrapper around url.URL - compare by value
			fmt.Fprintf(b, "%sif a.%s.Value.String() != b.%s.Value.String() {\n", valueIndent, field.FieldName, field.FieldName)
			fmt.Fprintf(b, "%s\treturn false\n", valueIndent)
			fmt.Fprintf(b, "%s}\n", valueIndent)
		case field.IsDecimal:
			// Optional wrapper around decimal.Decimal - compare by value
			fmt.Fprintf(b, "%sif !a.%s.Value.Equal(b.%s.Value) {\n", valueIndent, field.FieldName, field.FieldName)
			fmt.Fprintf(b, "%s\treturn false\n", valueIndent)
			fmt.Fprintf(b, "%s}\n", valueIndent)
		case field.IsDeepOnly:
			// Optional wrapper around a value without == operator
			fmt.Fprintf(b, "%sif !validate.EqualDeep(a.%s.Value, b.%s.Value) {\n", valueIndent, field.FieldName, field.FieldName)
			fmt.Fprintf(b, "%s\treturn false\n", valueIndent)
			fmt.Fprintf(b, "%s}\n", valueIndent)
		default:
			// Optional wrapper around primitive - use !=
			fmt.Fprintf(b, "%sif a.%s.Value != b.%s.Value {\n", valueIndent, field.FieldName, field.FieldName)
			fmt.Fprintf(b, "%s\treturn false\n", valueIndent)
			fmt.Fprintf(b, "%s}\n", valueIndent)
		}
		if field.IsOptionalNullable {
			fmt.Fprintf(b, "\t\t}\n")
		}
		fmt.Fprintf(b, "\t}\n")

	case ir.FieldTypeNullable:
		// Nullable field comparison (NilT types)
		fmt.Fprintf(b, "\t// Compare nullable field: %s\n", field.FieldName)
		fmt.Fprintf(b, "\tif a.%s.Null != b.%s.Null {\n", field.FieldName, field.FieldName)
		fmt.Fprintf(b, "\t\treturn false\n")
		fmt.Fprintf(b, "\t}\n")
		fmt.Fprintf(b, "\tif !a.%s.Null {\n", field.FieldName)
		switch {
		case field.IsNested:
			// Nullable wrapper around nested object - call Equal()
			if hasDepth {
				fmt.Fprintf(b, "\t\tif !a.%s.Value.Equal(b.%s.Value, depth+1) {\n", field.FieldName, field.FieldName)
			} else {
				fmt.Fprintf(b, "\t\tif !a.%s.Value.Equal(b.%s.Value) {\n", field.FieldName, field.FieldName)
			}
			fmt.Fprintf(b, "\t\t\treturn false\n")
			fmt.Fprintf(b, "\t\t}\n")
		case field.IsMap:
			// Nullable wrapper around map - need custom comparison
			g.writeMapComparison(b, fmt.Sprintf("a.%s.Value", field.FieldName), fmt.Sprintf("b.%s.Value", field.FieldName), "\t\t", field, hasDepth)
		case field.IsArray:
			// Nullable wrapper around array - need iteration
			aArray := fmt.Sprintf("a.%s.Value", field.FieldName)
			bArray := fmt.Sprintf("b.%s.Value", field.FieldName)
			g.writeArrayComparisonWithNullable(b, aArray, bArray, "\t\t", field, hasDepth)
		case field.IsRawJSON:
			// Nullable wrapper around raw JSON - compare semantically
			fmt.Fprintf(b, "\t\tif !validate.EqualRawJSON(a.%s.Value, b.%s.Value) {\n", field.FieldName, field.FieldName)
			fmt.Fprintf(b, "\t\t\treturn false\n")
			fmt.Fprintf(b, "\t\t}\n")
		case field.IsByteSlice:
			// Nullable wrapper around byte slice - use bytes.Equal()
			fmt.Fprintf(b, "\t\tif !bytes.Equal(a.%s.Value, b.%s.Value) {\n", field.FieldName, field.FieldName)
			fmt.Fprintf(b, "\t\t\treturn false\n")
			fmt.Fprintf(b, "\t\t}\n")
		case field.IsURL:
			// Nullable wrapper around url.URL - compare by value
			fmt.Fprintf(b, "\t\tif a.%s.Value.String() != b.%s.Value.String() {\n", field.FieldName, field.FieldName)
			fmt.Fprintf(b, "\t\t\treturn false\n")
			fmt.Fprintf(b, "\t\t}\n")
		case field.IsDecimal:
			// Nullable wrapper around decimal.Decimal - compare by value
			fmt.Fprintf(b, "\t\tif !a.%s.Value.Equal(b.%s.Value) {\n", field.FieldName, field.FieldName)
			fmt.Fprintf(b, "\t\t\treturn false\n")
			fmt.Fprintf(b, "\t\t}\n")
		case field.IsDeepOnly:
			// Nullable wrapper around a value without == operator
			fmt.Fprintf(b, "\t\tif !validate.EqualDeep(a.%s.Value, b.%s.Value) {\n", field.FieldName, field.FieldName)
			fmt.Fprintf(b, "\t\t\treturn false\n")
			fmt.Fprintf(b, "\t\t}\n")
		default:
			// Nullable wrapper around primitive - use !=
			fmt.Fprintf(b, "\t\tif a.%s.Value != b.%s.Value {\n", field.FieldName, field.FieldName)
			fmt.Fprintf(b, "\t\t\treturn false\n")
			fmt.Fprintf(b, "\t\t}\n")
		}
		fmt.Fprintf(b, "\t}\n")

	case ir.FieldTypePointer:
		// Pointer field comparison
		fmt.Fprintf(b, "\t// Compare pointer field: %s\n", field.FieldName)
		if field.IsDeepOnly {
			// Pointee has no == operator; validate.EqualDeep dereferences
			// pointers, handles nil on either side and keeps nested raw
			// JSON semantic
			fmt.Fprintf(b, "\tif !validate.EqualDeep(a.%s, b.%s) {\n", field.FieldName, field.FieldName)
			fmt.Fprintf(b, "\t\treturn false\n")
			fmt.Fprintf(b, "\t}\n")
			return
		}
		fmt.Fprintf(b, "\tif (a.%s == nil) != (b.%s == nil) {\n", field.FieldName, field.FieldName)
		fmt.Fprintf(b, "\t\treturn false\n")
		fmt.Fprintf(b, "\t}\n")
		fmt.Fprintf(b, "\tif a.%s != nil {\n", field.FieldName)
		if field.IsNested {
			// Pointer to a nested object - compare via Equal() on the pointee
			if hasDepth {
				fmt.Fprintf(b, "\t\tif !a.%s.Equal(*b.%s, depth+1) {\n", field.FieldName, field.FieldName)
			} else {
				fmt.Fprintf(b, "\t\tif !a.%s.Equal(*b.%s) {\n", field.FieldName, field.FieldName)
			}
		} else {
			fmt.Fprintf(b, "\t\tif *a.%s != *b.%s {\n", field.FieldName, field.FieldName)
		}
		fmt.Fprintf(b, "\t\t\treturn false\n")
		fmt.Fprintf(b, "\t\t}\n")
		fmt.Fprintf(b, "\t}\n")

	case ir.FieldTypeArray:
		// Array field comparison
		fmt.Fprintf(b, "\t// Compare array field: %s\n", field.FieldName)
		if field.IsArrayOfDeep {
			// Elements have no == operator and no generated Equal method.
			// validate.EqualDeep distinguishes nil from empty slices, which
			// covers nil-semantic arrays, and compares nested raw JSON
			// semantically
			fmt.Fprintf(b, "\tif !validate.EqualDeep(a.%s, b.%s) {\n", field.FieldName, field.FieldName)
			fmt.Fprintf(b, "\t\treturn false\n")
			fmt.Fprintf(b, "\t}\n")
			return
		}
		if field.IsNilSemanticArray {
			// nil encodes an absent or null property, which differs from []
			fmt.Fprintf(b, "\tif (a.%s == nil) != (b.%s == nil) {\n", field.FieldName, field.FieldName)
			fmt.Fprintf(b, "\t\treturn false\n")
			fmt.Fprintf(b, "\t}\n")
		}
		fmt.Fprintf(b, "\tif len(a.%s) != len(b.%s) {\n", field.FieldName, field.FieldName)
		fmt.Fprintf(b, "\t\treturn false\n")
		fmt.Fprintf(b, "\t}\n")
		fmt.Fprintf(b, "\tfor i := range a.%s {\n", field.FieldName)
		// Check if array elements are nullable wrappers
		switch {
		case field.IsArrayOfRaw:
			// Raw JSON elements - compare semantically
			fmt.Fprintf(b, "\t\tif !validate.EqualRawJSON(a.%s[i], b.%s[i]) {\n", field.FieldName, field.FieldName)
			fmt.Fprintf(b, "\t\t\treturn false\n")
			fmt.Fprintf(b, "\t\t}\n")
		case field.IsArrayOfNullable:
			// Nullable wrapper elements - compare Null flag then Value
			fmt.Fprintf(b, "\t\tif a.%s[i].Null != b.%s[i].Null {\n", field.FieldName, field.FieldName)
			fmt.Fprintf(b, "\t\t\treturn false\n")
			fmt.Fprintf(b, "\t\t}\n")
			fmt.Fprintf(b, "\t\tif !a.%s[i].Null {\n", field.FieldName)
			// Check if the wrapped value is a struct (needs Equal()) or primitive (use !=)
			if field.IsArrayOfStructs {
				// Value is a struct - call Equal()
				if hasDepth {
					fmt.Fprintf(b, "\t\t\tif !a.%s[i].Value.Equal(b.%s[i].Value, depth+1) {\n", field.FieldName, field.FieldName)
				} else {
					fmt.Fprintf(b, "\t\t\tif !a.%s[i].Value.Equal(b.%s[i].Value) {\n", field.FieldName, field.FieldName)
				}
			} else {
				// Value is a primitive - use !=
				fmt.Fprintf(b, "\t\t\tif a.%s[i].Value != b.%s[i].Value {\n", field.FieldName, field.FieldName)
			}
			fmt.Fprintf(b, "\t\t\t\treturn false\n")
			fmt.Fprintf(b, "\t\t\t}\n")
			fmt.Fprintf(b, "\t\t}\n")
		case field.IsArrayOfStructs:
			// Struct elements - call Equal()
			if hasDepth {
				fmt.Fprintf(b, "\t\tif !a.%s[i].Equal(b.%s[i], depth+1) {\n", field.FieldName, field.FieldName)
			} else {
				fmt.Fprintf(b, "\t\tif !a.%s[i].Equal(b.%s[i]) {\n", field.FieldName, field.FieldName)
			}
			fmt.Fprintf(b, "\t\t\treturn false\n")
			fmt.Fprintf(b, "\t\t}\n")
		default:
			// Primitive elements can use !=
			fmt.Fprintf(b, "\t\tif a.%s[i] != b.%s[i] {\n", field.FieldName, field.FieldName)
			fmt.Fprintf(b, "\t\t\treturn false\n")
			fmt.Fprintf(b, "\t\t}\n")
		}
		fmt.Fprintf(b, "\t}\n")

	case ir.FieldTypeMap:
		// Map field comparison
		fmt.Fprintf(b, "\t// Compare map field: %s\n", field.FieldName)
		g.writeMapComparison(b, fmt.Sprintf("a.%s", field.FieldName), fmt.Sprintf("b.%s", field.FieldName), "\t", field, hasDepth)

	case ir.FieldTypeNestedObject:
		// Nested object comparison (recursive Equal() call)
		fmt.Fprintf(b, "\t// Compare nested object: %s\n", field.FieldName)
		if hasDepth {
			fmt.Fprintf(b, "\tif !a.%s.Equal(b.%s, depth+1) {\n", field.FieldName, field.FieldName)
		} else {
			fmt.Fprintf(b, "\tif !a.%s.Equal(b.%s) {\n", field.FieldName, field.FieldName)
		}
		fmt.Fprintf(b, "\t\treturn false\n")
		fmt.Fprintf(b, "\t}\n")
	}
}

// generateHashMethod generates a Hash() method for a type
func (g *Generator) generateHashMethod(spec *ir.EqualityMethodSpec, pkgName string, fs FileSystem) error {
	var b strings.Builder

	// File header comment
	fmt.Fprintf(&b, "// Code generated by ogen, DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkgName)

	// Imports
	fmt.Fprintf(&b, "import (\n")
	fmt.Fprintf(&b, "\t\"encoding/binary\"\n")
	fmt.Fprintf(&b, "\t\"fmt\"\n")
	fmt.Fprintf(&b, "\t\"hash/fnv\"\n")
	fmt.Fprintf(&b, "\t\"sort\"\n\n")
	fmt.Fprintf(&b, "\t\"github.com/ogen-go/ogen/validate\"\n")
	fmt.Fprintf(&b, ")\n\n")

	// Method signature
	fmt.Fprintf(&b, "// Hash computes a hash value for %s using FNV-1a.\n", spec.TypeName)
	fmt.Fprintf(&b, "// Equal objects must produce equal hashes.\n")
	if spec.NeedsDepthTracking {
		fmt.Fprintf(&b, "// The depth parameter prevents infinite recursion on nested objects.\n")
		fmt.Fprintf(&b, "func (a %s) Hash(depth int) uint64 {\n", spec.TypeName)

		// Depth limit check
		fmt.Fprintf(&b, "\tif depth > %d {\n", spec.MaxDepth)
		fmt.Fprintf(&b, "\t\tpanic(&validate.DepthLimitError{\n")
		fmt.Fprintf(&b, "\t\t\tMaxDepth: %d,\n", spec.MaxDepth)
		fmt.Fprintf(&b, "\t\t\tTypeName: %q,\n", spec.TypeName)
		fmt.Fprintf(&b, "\t\t})\n")
		fmt.Fprintf(&b, "\t}\n\n")
	} else {
		fmt.Fprintf(&b, "func (a %s) Hash() uint64 {\n", spec.TypeName)
	}

	// Initialize hash
	fmt.Fprintf(&b, "\th := fnv.New64a()\n\n")

	// Hash each field
	for _, field := range spec.Fields {
		// Convert FieldEqualitySpec to FieldHashSpec
		hashField := ir.FieldHashSpec{
			FieldName:          field.FieldName,
			FieldType:          field.FieldType,
			GoType:             field.GoType,
			IsNested:           field.IsNested,
			IsArrayOfStructs:   field.IsArrayOfStructs,
			IsArrayOfNullable:  field.IsArrayOfNullable,
			IsMapOfStructs:     field.IsMapOfStructs,
			IsMapOfFloats:      field.IsMapOfFloats,
			IsMap:              field.IsMap,
			IsArray:            field.IsArray,
			IsRawJSON:          field.IsRawJSON,
			IsURL:              field.IsURL,
			IsDecimal:          field.IsDecimal,
			IsDeepOnly:         field.IsDeepOnly,
			IsArrayOfRaw:       field.IsArrayOfRaw,
			IsArrayOfDeep:      field.IsArrayOfDeep,
			IsMapOfRaw:         field.IsMapOfRaw,
			IsMapOfDeep:        field.IsMapOfDeep,
			IsOptionalNullable: field.IsOptionalNullable,
		}
		g.writeFieldHash(&b, hashField, spec.NeedsDepthTracking)
	}

	fmt.Fprintf(&b, "\treturn h.Sum64()\n")
	fmt.Fprintf(&b, "}\n")

	// Write to file
	filename := fmt.Sprintf("oas_%s_hash_gen.go", snakeCase(spec.TypeName))
	return writeFormattedCode(fs, filename, []byte(b.String()))
}

// isFloatGoType reports whether a Go type formats negative zero differently
// from positive zero under %v, breaking hash and equality coherence
func isFloatGoType(goType string) bool {
	return goType == "float32" || goType == "float64"
}

// elemGoType returns the element type of a slice Go type
func elemGoType(goType string) string {
	return strings.TrimPrefix(goType, "[]")
}

// nullableWrapsFloat reports whether a NilT wrapper element holds a float value
func nullableWrapsFloat(elemType string) bool {
	return elemType == "NilFloat32" || elemType == "NilFloat64"
}

// writeFloatHash emits a hash write that normalizes negative zero so values
// the Equal() comparison treats as equal produce equal hashes
func writeFloatHash(b *strings.Builder, indent, name, expr string) {
	fmt.Fprintf(b, "%s%s := %s\n", indent, name, expr)
	fmt.Fprintf(b, "%sif %s == 0 {\n", indent, name)
	fmt.Fprintf(b, "%s\t%s = 0\n", indent, name)
	fmt.Fprintf(b, "%s}\n", indent)
	fmt.Fprintf(b, "%sh.Write([]byte(fmt.Sprintf(\"%%v\", %s)))\n", indent, name)
}

// writeFieldHash generates hashing code for a single field.
//
// Every write must be derivable from the data the generated Equal() method
// compares: fields or payloads Equal() ignores, and representations it does
// not distinguish, must not feed the hash, or equal values could land in
// different buckets. Skipping a field entirely is always safe, because
// colliding values are resolved by Equal().
func (g *Generator) writeFieldHash(b *strings.Builder, field ir.FieldHashSpec, hasDepth bool) {
	nestedHashCall := func(expr string) string {
		if hasDepth {
			return fmt.Sprintf("%s.Hash(depth+1)", expr)
		}
		return fmt.Sprintf("%s.Hash()", expr)
	}

	switch field.FieldType {
	case ir.FieldTypePrimitive:
		if field.IsURL {
			// url.URL formatting through %v exposes pointer fields, so hash
			// the canonical string the Equal comparison uses
			fmt.Fprintf(b, "\t// Hash URL field by value: %s\n", field.FieldName)
			fmt.Fprintf(b, "\th.Write([]byte(a.%s.String()))\n", field.FieldName)
			return
		}
		if field.IsDecimal {
			// Equal decimals can format differently, so the field is excluded
			fmt.Fprintf(b, "\t// Field %s is excluded from the hash: equal decimals can format differently\n", field.FieldName)
			return
		}
		if field.IsRawJSON || field.IsDeepOnly {
			// Equality for this field ignores representation details the
			// formatted bytes would expose
			fmt.Fprintf(b, "\t// Field %s is excluded from the hash: its equality ignores representation details\n", field.FieldName)
			return
		}
		// Hash primitive field
		fmt.Fprintf(b, "\t// Hash primitive field: %s\n", field.FieldName)
		if isFloatGoType(field.GoType) {
			writeFloatHash(b, "\t", "v"+field.FieldName, "a."+field.FieldName)
		} else {
			fmt.Fprintf(b, "\th.Write([]byte(fmt.Sprintf(\"%%v\", a.%s)))\n", field.FieldName)
		}

	case ir.FieldTypeOptional:
		// Hash optional field (presence + value)
		fmt.Fprintf(b, "\t// Hash optional field: %s\n", field.FieldName)
		fmt.Fprintf(b, "\tif a.%s.Set {\n", field.FieldName)
		fmt.Fprintf(b, "\t\th.Write([]byte{1})\n")
		valueIndent := "\t\t"
		if field.IsOptionalNullable {
			// The null state participates in equality, and the inactive
			// payload under it does not
			fmt.Fprintf(b, "\t\tif a.%s.Null {\n", field.FieldName)
			fmt.Fprintf(b, "\t\t\th.Write([]byte{0})\n")
			fmt.Fprintf(b, "\t\t} else {\n")
			fmt.Fprintf(b, "\t\t\th.Write([]byte{1})\n")
			valueIndent = "\t\t\t"
		}
		g.writeWrappedValueHash(b, field, valueIndent, "a."+field.FieldName+".Value", nestedHashCall)
		if field.IsOptionalNullable {
			fmt.Fprintf(b, "\t\t}\n")
		}
		fmt.Fprintf(b, "\t} else {\n")
		fmt.Fprintf(b, "\t\th.Write([]byte{0})\n")
		fmt.Fprintf(b, "\t}\n")

	case ir.FieldTypeNullable:
		// Hash nullable field
		fmt.Fprintf(b, "\t// Hash nullable field: %s\n", field.FieldName)
		fmt.Fprintf(b, "\tif a.%s.Null {\n", field.FieldName)
		fmt.Fprintf(b, "\t\th.Write([]byte{0})\n")
		fmt.Fprintf(b, "\t} else {\n")
		fmt.Fprintf(b, "\t\th.Write([]byte{1})\n")
		g.writeWrappedValueHash(b, field, "\t\t", "a."+field.FieldName+".Value", nestedHashCall)
		fmt.Fprintf(b, "\t}\n")

	case ir.FieldTypePointer:
		// Hash pointer field
		fmt.Fprintf(b, "\t// Hash pointer field: %s\n", field.FieldName)
		fmt.Fprintf(b, "\tif a.%s != nil {\n", field.FieldName)
		fmt.Fprintf(b, "\t\th.Write([]byte{1})\n")
		switch {
		case field.IsNested:
			// Pointer to a nested object - call Hash()
			fmt.Fprintf(b, "\t\tnestedHash%s := %s\n", field.FieldName, nestedHashCall("a."+field.FieldName))
			fmt.Fprintf(b, "\t\tbinary.Write(h, binary.LittleEndian, nestedHash%s)\n", field.FieldName)
		case field.IsRawJSON, field.IsDeepOnly:
			fmt.Fprintf(b, "\t\t// Pointee excluded from the hash: its equality ignores representation details\n")
		case isFloatGoType(field.GoType):
			writeFloatHash(b, "\t\t", "v"+field.FieldName, "*a."+field.FieldName)
		default:
			fmt.Fprintf(b, "\t\th.Write([]byte(fmt.Sprintf(\"%%v\", *a.%s)))\n", field.FieldName)
		}
		fmt.Fprintf(b, "\t} else {\n")
		fmt.Fprintf(b, "\t\th.Write([]byte{0})\n")
		fmt.Fprintf(b, "\t}\n")

	case ir.FieldTypeArray:
		if field.IsArrayOfRaw || field.IsArrayOfDeep {
			// Equal() compares these elements semantically, no element
			// formatting is guaranteed stable across equal values
			fmt.Fprintf(b, "\t// Array field %s is excluded from the hash: its elements compare semantically\n", field.FieldName)
			return
		}
		// Hash array field
		fmt.Fprintf(b, "\t// Hash array field: %s\n", field.FieldName)
		fmt.Fprintf(b, "\tfor _, item := range a.%s {\n", field.FieldName)
		switch {
		case field.IsArrayOfNullable:
			// Hash the null state, then only the active value, so inactive
			// wrapper payloads cannot split equal items into different buckets
			fmt.Fprintf(b, "\t\tif item.Null {\n")
			fmt.Fprintf(b, "\t\t\th.Write([]byte{0})\n")
			fmt.Fprintf(b, "\t\t} else {\n")
			fmt.Fprintf(b, "\t\t\th.Write([]byte{1})\n")
			if field.IsArrayOfStructs {
				fmt.Fprintf(b, "\t\t\tbinary.Write(h, binary.LittleEndian, %s)\n", nestedHashCall("item.Value"))
			} else if nullableWrapsFloat(elemGoType(field.GoType)) {
				writeFloatHash(b, "\t\t\t", "v", "item.Value")
			} else {
				fmt.Fprintf(b, "\t\t\th.Write([]byte(fmt.Sprintf(\"%%v\", item.Value)))\n")
			}
			fmt.Fprintf(b, "\t\t}\n")
		case field.IsArrayOfStructs:
			// Struct elements provide their own equality-consistent Hash()
			fmt.Fprintf(b, "\t\tbinary.Write(h, binary.LittleEndian, %s)\n", nestedHashCall("item"))
		case isFloatGoType(elemGoType(field.GoType)):
			writeFloatHash(b, "\t\t", "v", "item")
		default:
			fmt.Fprintf(b, "\t\th.Write([]byte(fmt.Sprintf(\"%%v\", item)))\n")
		}
		fmt.Fprintf(b, "\t}\n")

	case ir.FieldTypeMap:
		// Hash map field (sorted keys for deterministic hash)
		fmt.Fprintf(b, "\t// Hash map field: %s (sorted keys)\n", field.FieldName)
		fmt.Fprintf(b, "\tkeys%s := make([]string, 0, len(a.%s))\n", field.FieldName, field.FieldName)
		fmt.Fprintf(b, "\tfor k := range a.%s {\n", field.FieldName)
		fmt.Fprintf(b, "\t\tkeys%s = append(keys%s, k)\n", field.FieldName, field.FieldName)
		fmt.Fprintf(b, "\t}\n")
		fmt.Fprintf(b, "\tsort.Strings(keys%s)\n", field.FieldName)
		fmt.Fprintf(b, "\tfor _, k := range keys%s {\n", field.FieldName)
		fmt.Fprintf(b, "\t\th.Write([]byte(k))\n")
		switch {
		case field.IsMapOfStructs:
			// Struct values provide their own equality-consistent Hash()
			fmt.Fprintf(b, "\t\tbinary.Write(h, binary.LittleEndian, %s)\n", nestedHashCall(fmt.Sprintf("a.%s[k]", field.FieldName)))
		case field.IsMapOfRaw, field.IsMapOfDeep:
			// Values compare semantically, so only the keys feed the hash
			fmt.Fprintf(b, "\t\t// Map values excluded from the hash: they compare semantically\n")
		case field.IsMapOfFloats:
			writeFloatHash(b, "\t\t", "v", fmt.Sprintf("a.%s[k]", field.FieldName))
		default:
			fmt.Fprintf(b, "\t\th.Write([]byte(fmt.Sprintf(\"%%v\", a.%s[k])))\n", field.FieldName)
		}
		fmt.Fprintf(b, "\t}\n")

	case ir.FieldTypeNestedObject:
		// Hash nested object (incorporate its Hash() result)
		fmt.Fprintf(b, "\t// Hash nested object: %s\n", field.FieldName)
		fmt.Fprintf(b, "\tnestedHash%s := %s\n", field.FieldName, nestedHashCall("a."+field.FieldName))
		fmt.Fprintf(b, "\tbinary.Write(h, binary.LittleEndian, nestedHash%s)\n", field.FieldName)
	}
}

// writeWrappedValueHash emits hashing code for the active value of an
// Optional or Nullable wrapper
func (g *Generator) writeWrappedValueHash(b *strings.Builder, field ir.FieldHashSpec, indent, expr string, nestedHashCall func(string) string) {
	switch {
	case field.IsNested:
		// Wrapper around nested object - call Hash()
		fmt.Fprintf(b, "%snestedHash%s := %s\n", indent, field.FieldName, nestedHashCall(expr))
		fmt.Fprintf(b, "%sbinary.Write(h, binary.LittleEndian, nestedHash%s)\n", indent, field.FieldName)
	case field.IsURL:
		fmt.Fprintf(b, "%sh.Write([]byte(%s.String()))\n", indent, expr)
	case field.IsDecimal:
		fmt.Fprintf(b, "%s// Wrapped decimal excluded from the hash: equal decimals can format differently\n", indent)
	case field.IsMap || field.IsArray || field.IsRawJSON || field.IsDeepOnly:
		// Formatting a wrapped container or semantic value would expose
		// representation details that Equal() ignores, such as inactive
		// nested wrapper payloads, signed zero, or raw JSON bytes. The
		// presence markers already written keep the hash discriminating
		fmt.Fprintf(b, "%s// Wrapped value excluded from the hash: only its presence participates\n", indent)
	case isFloatGoType(field.GoType):
		writeFloatHash(b, indent, "v"+field.FieldName, expr)
	default:
		fmt.Fprintf(b, "%sh.Write([]byte(fmt.Sprintf(\"%%v\", %s)))\n", indent, expr)
	}
}

// writeFormattedCode formats and writes code to a file using FileSystem
func writeFormattedCode(fs FileSystem, filename string, content []byte) error {
	// Format with goimports
	formatted, err := imports.Process(filename, content, nil)
	if err != nil {
		// If formatting fails, return error (don't write malformed code)
		return errors.Wrap(err, "format code")
	}

	// Write to file using FileSystem interface
	if fs != nil {
		return fs.WriteFile(filename, formatted)
	}

	// Fallback to os.WriteFile for testing
	return os.WriteFile(filename, formatted, 0644)
}

// snakeCase converts PascalCase to snake_case
func snakeCase(s string) string {
	var result strings.Builder
	for i, r := range s {
		if i > 0 && r >= 'A' && r <= 'Z' {
			result.WriteRune('_')
		}
		result.WriteRune(r)
	}
	return strings.ToLower(result.String())
}

// writeMapComparison generates map comparison code
func (g *Generator) writeMapComparison(b *strings.Builder, aMap, bMap, indent string, field ir.FieldEqualitySpec, hasDepth bool) {
	fmt.Fprintf(b, "%sif len(%s) != len(%s) {\n", indent, aMap, bMap)
	fmt.Fprintf(b, "%s\treturn false\n", indent)
	fmt.Fprintf(b, "%s}\n", indent)
	fmt.Fprintf(b, "%sfor k, v := range %s {\n", indent, aMap)
	switch {
	case field.IsMapOfStructs:
		// Struct values - recurse through Equal() for semantic comparison
		fmt.Fprintf(b, "%s\tbv, ok := %s[k]\n", indent, bMap)
		fmt.Fprintf(b, "%s\tif !ok {\n", indent)
		fmt.Fprintf(b, "%s\t\treturn false\n", indent)
		fmt.Fprintf(b, "%s\t}\n", indent)
		if hasDepth {
			fmt.Fprintf(b, "%s\tif !v.Equal(bv, depth+1) {\n", indent)
		} else {
			fmt.Fprintf(b, "%s\tif !v.Equal(bv) {\n", indent)
		}
		fmt.Fprintf(b, "%s\t\treturn false\n", indent)
		fmt.Fprintf(b, "%s\t}\n", indent)
	case field.IsMapOfRaw:
		// Raw JSON values - compare semantically
		fmt.Fprintf(b, "%s\tbv, ok := %s[k]\n", indent, bMap)
		fmt.Fprintf(b, "%s\tif !ok || !validate.EqualRawJSON(v, bv) {\n", indent)
		fmt.Fprintf(b, "%s\t\treturn false\n", indent)
		fmt.Fprintf(b, "%s\t}\n", indent)
	case field.IsMapOfDeep:
		// Values without == operator
		fmt.Fprintf(b, "%s\tbv, ok := %s[k]\n", indent, bMap)
		fmt.Fprintf(b, "%s\tif !ok || !validate.EqualDeep(v, bv) {\n", indent)
		fmt.Fprintf(b, "%s\t\treturn false\n", indent)
		fmt.Fprintf(b, "%s\t}\n", indent)
	default:
		// Primitive values - direct comparison
		fmt.Fprintf(b, "%s\tif bv, ok := %s[k]; !ok || v != bv {\n", indent, bMap)
		fmt.Fprintf(b, "%s\t\treturn false\n", indent)
		fmt.Fprintf(b, "%s\t}\n", indent)
	}
	fmt.Fprintf(b, "%s}\n", indent)
}

// writeArrayComparisonWithNullable generates array comparison code with nullable support
func (g *Generator) writeArrayComparisonWithNullable(
	b *strings.Builder, aArray, bArray, indent string,
	field ir.FieldEqualitySpec, hasDepth bool,
) {
	isArrayOfStructs := field.IsArrayOfStructs
	if field.IsArrayOfDeep {
		// Elements have no == operator and no generated Equal method
		fmt.Fprintf(b, "%sif !validate.EqualDeep(%s, %s) {\n", indent, aArray, bArray)
		fmt.Fprintf(b, "%s\treturn false\n", indent)
		fmt.Fprintf(b, "%s}\n", indent)
		return
	}
	fmt.Fprintf(b, "%sif len(%s) != len(%s) {\n", indent, aArray, bArray)
	fmt.Fprintf(b, "%s\treturn false\n", indent)
	fmt.Fprintf(b, "%s}\n", indent)
	fmt.Fprintf(b, "%sfor i := range %s {\n", indent, aArray)
	switch {
	case field.IsArrayOfRaw:
		// Raw JSON elements - compare semantically
		fmt.Fprintf(b, "%s\tif !validate.EqualRawJSON(%s[i], %s[i]) {\n", indent, aArray, bArray)
		fmt.Fprintf(b, "%s\t\treturn false\n", indent)
		fmt.Fprintf(b, "%s\t}\n", indent)
	case field.IsArrayOfNullable:
		// Nullable wrapper elements - compare Null flag then Value
		fmt.Fprintf(b, "%s\tif %s[i].Null != %s[i].Null {\n", indent, aArray, bArray)
		fmt.Fprintf(b, "%s\t\treturn false\n", indent)
		fmt.Fprintf(b, "%s\t}\n", indent)
		fmt.Fprintf(b, "%s\tif !%s[i].Null {\n", indent, aArray)
		// Check if the wrapped value is a struct (needs Equal()) or primitive (use !=)
		if isArrayOfStructs {
			// Value is a struct - call Equal()
			if hasDepth {
				fmt.Fprintf(b, "%s\t\tif !%s[i].Value.Equal(%s[i].Value, depth+1) {\n", indent, aArray, bArray)
			} else {
				fmt.Fprintf(b, "%s\t\tif !%s[i].Value.Equal(%s[i].Value) {\n", indent, aArray, bArray)
			}
		} else {
			// Value is a primitive - use !=
			fmt.Fprintf(b, "%s\t\tif %s[i].Value != %s[i].Value {\n", indent, aArray, bArray)
		}
		fmt.Fprintf(b, "%s\t\t\treturn false\n", indent)
		fmt.Fprintf(b, "%s\t\t}\n", indent)
		fmt.Fprintf(b, "%s\t}\n", indent)
	case isArrayOfStructs:
		// Array elements are structs - call Equal()
		if hasDepth {
			fmt.Fprintf(b, "%s\tif !%s[i].Equal(%s[i], depth+1) {\n", indent, aArray, bArray)
		} else {
			fmt.Fprintf(b, "%s\tif !%s[i].Equal(%s[i]) {\n", indent, aArray, bArray)
		}
		fmt.Fprintf(b, "%s\t\treturn false\n", indent)
		fmt.Fprintf(b, "%s\t}\n", indent)
	default:
		// Primitive elements can use !=
		fmt.Fprintf(b, "%s\tif %s[i] != %s[i] {\n", indent, aArray, bArray)
		fmt.Fprintf(b, "%s\t\treturn false\n", indent)
		fmt.Fprintf(b, "%s\t}\n", indent)
	}
	fmt.Fprintf(b, "%s}\n", indent)
}

// generateRawJSONEqualMethods generates semantic Equal() methods for named
// raw JSON alias types that participate in uniqueItems comparison, so the
// reflect-based deep comparison dispatches to them instead of comparing
// their bytes.
func (g *Generator) generateRawJSONEqualMethods(fs FileSystem, pkgName string) error {
	if len(g.rawJSONAliases) == 0 {
		return nil
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by ogen, DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkgName)
	fmt.Fprintf(&b, "import (\n")
	fmt.Fprintf(&b, "\t\"github.com/go-faster/jx\"\n\n")
	fmt.Fprintf(&b, "\t\"github.com/ogen-go/ogen/validate\"\n")
	fmt.Fprintf(&b, ")\n\n")
	for _, alias := range g.rawJSONAliases {
		fmt.Fprintf(&b, "// Equal reports whether both raw JSON values are semantically equal.\n")
		fmt.Fprintf(&b, "func (s %s) Equal(v %s) bool {\n", alias.Name, alias.Name)
		fmt.Fprintf(&b, "\treturn validate.EqualRawJSON(jx.Raw(s), jx.Raw(v))\n")
		fmt.Fprintf(&b, "}\n\n")
	}

	filename := fmt.Sprintf("%s_raw_json_equal_gen.go", snakeCase(pkgName))
	return writeFormattedCode(fs, filename, []byte(b.String()))
}
